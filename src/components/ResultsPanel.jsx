// ── Loading state with elapsed timer ─────────────────────────────────────────

function LoadingState() {
  const [elapsed, setElapsed] = useState(0)

  useEffect(() => {
    const id = setInterval(() => setElapsed((s) => s + 1), 1000)
    return () => clearInterval(id)
  }, [])

  const hint =
    elapsed < 5
      ? 'Searching GTPlanet community threads…'
      : elapsed < 15
        ? 'Generating setup recommendations…'
        : elapsed < 30
          ? 'Almost there — AI is finalising values…'
          : 'Taking a bit longer than usual, hang tight…'

  return (
    <div className="results-empty">
      <div className="results-loading">
        <div className="results-loading__spinner" />
        <p>{hint}</p>
        <span className="results-loading__timer">{elapsed}s</span>
        <span className="results-loading__note">
          First lookup takes 15–30 s. Results are cached after that.
        </span>
      </div>
    </div>
  )
}

