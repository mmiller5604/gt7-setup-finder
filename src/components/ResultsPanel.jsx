// ── Helpers ──────────────────────────────────────────────────────────────────

/** Build plain-text representation of a setup for clipboard copy. */
function buildCopyText(title, car, track, setup) {
  const lines = [`${title} — ${car} at ${track}`, '']
  for (const section of SECTIONS) {
    const data = setup?.[section.key] ?? {}
    const visible = section.fields.filter((f) => data[f.key] && data[f.key] !== 'N/A')
    if (!visible.length) continue
    lines.push(`── ${section.label} ──`)
    for (const field of visible) {
      lines.push(`  ${field.label}: ${data[field.key]}${field.unit}`)
    }
    lines.push('')
  }
  if (setup?._source_url) lines.push(`Source: ${setup._source_url}`)
  lines.push('\nGenerated by GT7 Setup Finder (gt7setup.app)')
  return lines.join('\n')
}

// ── Sub-components ───────────────────────────────────────────────────────────

function SetupSection({ section, setup }) {
  const sectionData = setup?.[section.key] ?? {}
  const visibleFields = section.fields.filter(
    (f) => sectionData[f.key] && sectionData[f.key] !== 'N/A',
  )
  if (!visibleFields.length) return null

  return (
    <div className="setup-section">
      <div className="setup-section__title">
        <span className="setup-section__icon" aria-hidden="true">{section.icon}</span>
        {section.label}
      </div>
      <table className="setup-table">
        <tbody>
          {visibleFields.map((field) => (
            <tr key={field.key} className="setup-table__row">
              <td className="setup-table__label">{field.label}</td>
              <td className="setup-table__value">
                {sectionData[field.key]}
                {field.unit && <span className="setup-table__unit">{field.unit}</span>}
              </td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  )
}

function CopyButton({ title, car, track, setup }) {
  const [copied, setCopied] = useState(false)

  const handleCopy = useCallback(async () => {
    try {
      await navigator.clipboard.writeText(buildCopyText(title, car, track, setup))
      setCopied(true)
      setTimeout(() => setCopied(false), 2000)
    } catch {
      // clipboard API unavailable — silently ignore
    }
  }, [title, car, track, setup])

  return (
    <button
      className={`copy-btn${copied ? ' copy-btn--copied' : ''}`}
      onClick={handleCopy}
      title="Copy setup to clipboard"
      aria-label="Copy setup to clipboard"
    >
      {copied ? (
        <>
          <svg width="13" height="13" viewBox="0 0 14 14" fill="none" aria-hidden="true">
            <path d="M2.5 7.5L5.5 10.5L11.5 4" stroke="currentColor" strokeWidth="1.6" strokeLinecap="round" strokeLinejoin="round"/>
          </svg>
          Copied!
        </>
      ) : (
        <>
          <svg width="13" height="13" viewBox="0 0 14 14" fill="none" aria-hidden="true">
            <rect x="1.5" y="4.5" width="8" height="9" rx="1.5" stroke="currentColor" strokeWidth="1.3"/>
            <path d="M4.5 4V3a1.5 1.5 0 0 1 1.5-1.5h5A1.5 1.5 0 0 1 12.5 3v7a1.5 1.5 0 0 1-1.5 1.5H10" stroke="currentColor" strokeWidth="1.3" strokeLinecap="round"/>
          </svg>
          Copy
        </>
      )}
    </button>
  )
}

